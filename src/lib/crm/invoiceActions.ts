import {
  invoiceErrorField,
  invoiceErrorMessage,
  issueDates,
  type Invoice,
  type IvaPct,
  type Sale,
} from "@/lib/crm/facturas";
import { createSupabaseBrowserClient } from "@/lib/supabase/browser";

// Invoice writes shared by the Facturas table, the invoice dialogs and the agent chat. The database triggers
// enforce every rule; each action only turns their errors into Spanish copy.

const supabase = createSupabaseBrowserClient();

const UPDATE_ERROR = "No se ha podido actualizar la factura. Inténtalo de nuevo.";
const SAVE_ERROR = "No se ha podido guardar la factura. Inténtalo de nuevo.";

// `field` names the form field the error belongs to (e.g. a duplicate number), when it is not form-level.
export type InvoiceActionResult = { error: string | null; numero?: string | null; field?: "numero" };

type DraftDates = { fecha_emision: string; fecha_vencimiento: string };
type Request<T> = PromiseLike<{ data: T | null; error: { message?: string } | null }>;

async function run<T>(request: Request<T>, fallback: string) {
  const { data, error } = await request;
  if (error || !data) {
    return { data: null, error: invoiceErrorMessage(error) ?? fallback, field: invoiceErrorField(error) ?? undefined };
  }
  return { data, error: null, field: undefined };
}

async function numeroOf(request: Request<{ numero: string | null }>, fallback: string): Promise<InvoiceActionResult> {
  const { data, error, field } = await run(request, fallback);
  return { error, numero: data?.numero ?? null, field };
}

function updateState(id: string, from: Invoice["estado"], changes: Partial<Invoice>, fallback = UPDATE_ERROR) {
  return numeroOf(
    supabase.from("facturas").update(changes).eq("id", id).eq("estado", from).select("numero").single(),
    fallback,
  );
}

// Issuing refreshes the base from the sale's current price and moves past dates to today.
export function issueDraft(
  invoice: Pick<Invoice, "id" | "fecha_emision" | "fecha_vencimiento" | "iva_pct">,
  precio: number,
  today: Date,
) {
  return updateState(invoice.id, "borrador", {
    ...issueDates(invoice, today),
    base: precio,
    iva_pct: invoice.iva_pct,
    estado: "pendiente",
  });
}

export function updateDraft(id: string, fields: DraftDates & { base: number; iva_pct: IvaPct }) {
  return updateState(id, "borrador", fields, SAVE_ERROR);
}

export function markPaid(id: string) {
  return updateState(id, "pendiente", { estado: "pagada" });
}

export function cancelInvoice(id: string) {
  return updateState(id, "pendiente", { estado: "anulada" });
}

export function deleteDraft(id: string) {
  return numeroOf(
    supabase.from("facturas").delete().eq("id", id).eq("estado", "borrador").select("numero").single(),
    UPDATE_ERROR,
  );
}

// Returns the new draft's id so a caller can issue it right away (or retry the issue) without inserting twice.
export async function createDraftFromSale(
  sale: Sale,
  dates: DraftDates,
  iva_pct: IvaPct,
): Promise<InvoiceActionResult & { id?: string }> {
  const { opportunity } = sale;
  if (opportunity.precio === null) return { error: "Esta venta no tiene precio. Añádelo antes de facturarla." };
  const { data, error } = await run<{ id: string }>(
    supabase
      .from("facturas")
      .insert({
        ...dates,
        base: opportunity.precio,
        iva_pct,
        oportunidad_id: opportunity.id,
        empresa_id: opportunity.empresa_id,
        estado: "borrador",
      })
      .select("id")
      .single(),
    SAVE_ERROR,
  );
  return data ? { error: null, id: String(data.id) } : { error };
}

// The id is generated by the caller, which has already uploaded the photo under `<id>/...`.
export function createPhotoInvoice(input: {
  id: string;
  empresa_id: string;
  numero: string;
  fecha_emision: string;
  fecha_vencimiento: string;
  base: number;
  iva_pct: IvaPct;
  pagada: boolean;
  foto_path: string;
}) {
  const { pagada, ...fields } = input;
  return numeroOf(
    supabase
      .from("facturas")
      .insert({ ...fields, origen: "foto", oportunidad_id: null, estado: pagada ? "pagada" : "pendiente" })
      .select("numero")
      .single(),
    SAVE_ERROR,
  );
}
